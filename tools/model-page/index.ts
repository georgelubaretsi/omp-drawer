// docs/model/index.md: every plugin in the catalog, with its "what the model sees" page, or none
// for a plugin that sends the model nothing. A plugin sends the model something when it ships a
// catalog (core/model.ftl), operations, rules or skills; such a plugin needs a scripted session
// (test/scenario.ts), so nothing it sends goes unshown.
import { existsSync } from "node:fs";
import { join } from "node:path";

export interface Listed {
	readonly name: string;
	readonly hosts: readonly string[];
}

const HOSTS: Readonly<Record<string, string>> = { omp: "omp", claude: "Claude Code", codex: "Codex", tern: "Tern" };

/** What in the plugin's folder `dir` reaches the model. */
function sends(dir: string): string[] {
	return ["core/model.ftl", "core/operations.json", "rules", "skills"].filter(part => existsSync(join(dir, part)));
}

/** The plugins that send the model something but have no scripted session, each with what it sends. */
export function unshown(root: string, plugins: readonly Listed[]): string[] {
	return plugins.flatMap(({ name }) => {
		const dir = join(root, "plugins", name);
		const parts = sends(dir);
		if (parts.length === 0 || existsSync(join(dir, "test", "scenario.ts"))) return [];
		return [`plugins/${name} sends the model ${parts.join(", ")} but has no test/scenario.ts to show it`];
	});
}

/** The index page, the plugins in catalog order; `modeled` are the ones with a page. */
export function indexPage(plugins: readonly Listed[], modeled: ReadonlySet<string>): string {
	const rows = plugins.map(({ name, hosts }) => {
		const where = hosts.map(host => HOSTS[host] ?? host).join(", ");
		return modeled.has(name)
			? `| [${name}](${name}.md) | ${where} |`
			: `| ${name} | ${where}; it sends the model nothing |`;
	});
	return [
		"# What the model sees",
		"",
		"Every text each plugin gives the model, word for word, in each harness it runs in: one page per",
		"plugin, from a made-up session run through its real shells (`plugins/<name>/test/scenario.ts`).",
		"",
		"| Plugin | Harnesses |",
		"| --- | --- |",
		...rows,
		"",
		"Generated by `bun tools/model-page.ts` (`just build`); `just check` fails when a page is out of",
		"date, and when a plugin that sends the model text has no scripted session.",
		"",
	].join("\n");
}
